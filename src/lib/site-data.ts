export function isOpenNow(now = new Date()) {
  const minutes = now.getHours() * 60 + now.getMinutes();
  // Open daily 10:00 AM (600 mins) to 9:00 PM (1260 mins)
  return minutes >= 10 * 60 && minutes < 21 * 60;
}
